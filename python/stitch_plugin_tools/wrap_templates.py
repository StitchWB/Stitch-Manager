_TEST_TEMPLATE = '''"""Protocol smoke test for the __PLUGIN_ID__ wrapped service plugin.

Spawns ``python -m __PKG_NAME__`` (no host dependency) and walks the
JSON-RPC 2.0 line protocol: init -> ping -> health_check -> shutdown.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

MODULE = "__PKG_NAME__"
PLUGIN_ID = "__PLUGIN_ID__"

PACKAGE_DIR = Path(__file__).resolve().parents[1]


def _request(rid: int, method: str, params: dict | None = None) -> str:
    return json.dumps(
        {"jsonrpc": "2.0", "id": rid, "method": method, "params": params or {}}
    )


def _drive(lines: list[str]) -> dict[int, dict]:
    proc = subprocess.run(
        [sys.executable, "-m", MODULE],
        input="\\n".join(lines) + "\\n",
        capture_output=True,
        text=True,
        encoding="utf-8",
        cwd=str(PACKAGE_DIR),
        timeout=30,
    )
    assert proc.returncode == 0, f"plugin exited {proc.returncode}: {proc.stderr}"
    responses: dict[int, dict] = {}
    for line in proc.stdout.splitlines():
        line = line.strip()
        if line:
            obj = json.loads(line)
            responses[obj["id"]] = obj
    return responses


def test_lifecycle_init_ping_command_shutdown() -> None:
    responses = _drive(
        [
            _request(
                1,
                "plugin.init",
                {
                    "engine_api": 2,
                    "plugin_id": PLUGIN_ID,
                    "db_path": "",
                    "data_dir": "",
                    "supported": [],
                },
            ),
            _request(2, "plugin.ping"),
            _request(3, "plugin.call", {"name": "health_check", "params": {}}),
            _request(4, "plugin.shutdown"),
        ]
    )

    init = responses[1]["result"]
    assert init["plugin_id"] == PLUGIN_ID
    assert init["capabilities"] == []

    assert responses[2]["result"] == "pong"
    assert responses[3]["result"]["pong"] is True

    assert responses[4]["result"] is None
'''

