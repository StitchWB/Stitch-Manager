UPGRADE_DIFF_FILENAME = "upgrade.diff"

#: Staging dir for atomic apply; if present at start an interrupted run left it and it is auto-cleaned.
UPGRADE_STAGING_DIR = ".upgrade-staging"


# ── Merge engine ─────────────────────────────────────────────────────────


@dataclass
class UpgradeReport:
    """Result of an upgrade run (preview or apply)."""

    package_dir: Path
    status: str  # legacy | newer | up-to-date | preview | applied | no-drift | apply_failed
    detected: DetectedVersion | None
    results: list[RegionResult] = field(default_factory=list)
    diff_path: Path | None = None
    message: str = ""
    warnings: list[str] = field(default_factory=list)

    @property
    def changed_any(self) -> bool:
        return any(r.changed for r in self.results)


def _write_preserve_eol(path: Path, lf_text: str, original: str) -> None:
    """Write LF text back with the file's original line-ending style."""
    if "\r\n" in original:
        lf_text = lf_text.replace("\n", "\r\n")
    path.write_bytes(lf_text.encode("utf-8"))


def _apply_upgraded_files(
    package_dir: Path,
    updated: dict[str, str],
    originals: dict[str, str],
) -> tuple[bool, str, list[str]]:
    """Stage + move upgraded files atomically.

    Phase 1 (stage): write every changed file into
    ``<package>/.upgrade-staging/`` mirroring the relative path.  On any
    write failure, the staging dir is removed and originals are untouched.

    Phase 2 (move): ``os.replace`` each staged file into its target
    location.  ``os.replace`` is a single atomic syscall (rename), so a
    crash mid-move can only leave the file being moved in a transient
    state — all other files are either fully old or fully new.  On a
    move failure, the failing file's original is untouched and the
    remaining staging files are cleaned up.

    Returns ``(success, error_message, warnings)``.  ``success`` is
    ``True`` when all files were staged + moved.  ``error_message`` names
    the file that failed.  ``warnings`` includes the resume-guard notice
    when an interrupted staging dir was found and cleaned.
    """
    warnings: list[str] = []
    staging_dir = package_dir / UPGRADE_STAGING_DIR

    # An existing staging dir means an interrupted apply; auto-clean and re-stage (user passed --apply).
    if staging_dir.is_dir():
        shutil.rmtree(staging_dir, ignore_errors=True)
        warnings.append(
            f"cleaned up interrupted previous upgrade staging dir "
            f"({UPGRADE_STAGING_DIR}/) — a prior --apply was interrupted"
        )

    # Collect files that actually changed.
    changed: list[tuple[str, str, str]] = [
        (rel, new_text, originals.get(rel, ""))
        for rel, new_text in updated.items()
        if new_text != originals.get(rel, "")
    ]
    if not changed:
        return True, "", warnings

    # Phase 1: Stage all updated files.
    staging_dir.mkdir(parents=True, exist_ok=True)
    staged: list[tuple[Path, Path]] = []  # (staged_path, target_path)
    try:
        for rel, new_text, original in changed:
            staged_path = staging_dir / rel
            staged_path.parent.mkdir(parents=True, exist_ok=True)
            _write_preserve_eol(staged_path, new_text, original)
            staged.append((staged_path, package_dir / rel))
    except Exception as exc:  # noqa: BLE001 — report any staging failure
        shutil.rmtree(staging_dir, ignore_errors=True)
        return False, f"staging failed for {rel}: {exc}", warnings

    # Phase 2: Move staged files into place (atomic per-file via os.replace).
    try:
        for staged_path, target in staged:
            target.parent.mkdir(parents=True, exist_ok=True)
            if (
                target.is_file()
                and target.as_posix().endswith(VENDOR_RPC_REL_SUFFIX)
            ):
                # Preserve the drifted vendor bytes before the atomic swap overwrites them.
                backup = target.parent / (target.name + VENDOR_BACKUP_SUFFIX)
                backup.write_bytes(target.read_bytes())
            os.replace(staged_path, target)
    except OSError as exc:
        # A move failed; earlier moves are already atomic and the failing file's original is untouched.
        shutil.rmtree(staging_dir, ignore_errors=True)
        rel = str(target.relative_to(package_dir))
        return False, f"move failed for {rel}: {exc}", warnings

    # Success — remove the (now empty) staging dir.
    shutil.rmtree(staging_dir, ignore_errors=True)
    return True, "", warnings


def upgrade_package(package_dir: Path, *, apply: bool = False) -> UpgradeReport:
    """Preview (default) or apply (``apply=True``) a scaffold upgrade.

    Always writes ``<package>/upgrade.diff`` before any modification when
    changes are pending; the diff file is removed after a successful apply.
    """
    package_dir = package_dir.resolve()
    detected = detect_scaffold_version(package_dir)

    if detected is None:
        return UpgradeReport(
            package_dir=package_dir,
            status="legacy",
            detected=None,
            message=(
                "legacy plugin, manual migration needed: no _generated_by "
                "marker, no manifest generated_by field, and no v2-era "
                "inline fallback block found (package predates scaffold v2)"
            ),
        )

    if detected.key > CURRENT_VERSION_KEY:
        return UpgradeReport(
            package_dir=package_dir,
            status="newer",
            detected=detected,
            message=(
                f"package was generated by scaffold {detected.label} — newer "
                f"than this tooling (v{SCAFFOLD_VERSION}); upgrade "
                "stitch_plugin_tools first"
            ),
        )

    # ── Module dir resolution ──────────────────────────────────────────
    module_dir = _package_module_dir(package_dir)
    module_rel = module_dir.name if module_dir is not None else None

    originals: dict[str, str] = {}
    updated: dict[str, str] = {}
    results: list[RegionResult] = []

    # ── Generation migration (v2→v3): runs when detected < current ────
    if detected.key < CURRENT_VERSION_KEY and module_dir is not None:
        _generation_migration(
            package_dir, module_dir, module_rel, originals, updated, results,
        )

    # ── Region normalization (runs for both v2→v3 and v3 drift) ──────
    for region_name, rel_template, rewrite in REGION_REGISTRY:
        rel = rel_template.format(module=module_rel) if module_rel else rel_template
        if "{module}" in rel:
            results.append(
                RegionResult(
                    region=region_name,
                    file=rel_template,
                    changed=False,
                    note="module directory not found",
                )
            )
            continue
        path = package_dir / rel
        # New files created by generation migration are already in updated.
        if not path.is_file() and rel in updated:
            # Vendor file just created by generation migration — check against canonical (no-op).
            new_text, note = rewrite(updated[rel])
            changed = new_text is not None
            if changed:
                updated[rel] = new_text  # type: ignore[assignment]
            results.append(RegionResult(
                region=region_name, file=rel, changed=changed, note=note,
            ))
            continue
        if not path.is_file():
            results.append(
                RegionResult(
                    region=region_name, file=rel, changed=False, note="file not found"
                )
            )
            continue
        if rel not in originals:
            originals[rel] = _read_lf(path)
            updated[rel] = originals[rel]
        new_text, note = rewrite(updated[rel])
        changed = new_text is not None
        if changed:
            updated[rel] = new_text  # type: ignore[assignment]
        results.append(RegionResult(region=region_name, file=rel, changed=changed, note=note))

    report = UpgradeReport(
        package_dir=package_dir, status="preview", detected=detected, results=results
    )

    if not report.changed_any:
        report.status = "no-drift"
        report.message = (
            f"package at scaffold {detected.label}: all canonical regions "
            "already match the current conventions — nothing to do"
        )
        return report

    # ── Diff preview (always written before any modification) ──────────
    diff_parts: list[str] = []
    for rel in sorted(originals):
        if originals[rel] == updated[rel]:
            continue
        diff_parts.extend(
            difflib.unified_diff(
                originals[rel].splitlines(),
                updated[rel].splitlines(),
                fromfile=f"a/{rel}",
                tofile=f"b/{rel}",
                lineterm="",
            )
        )
    diff_path = package_dir / UPGRADE_DIFF_FILENAME
    diff_path.write_text("\n".join(diff_parts) + "\n", encoding="utf-8")
    report.diff_path = diff_path

    if not apply:
        report.message = (
            f"preview written to {diff_path} — re-run with --apply to write "
            "the changes"
        )
        return report

    # ── Apply (atomic: stage → os.replace → cleanup) ───────────────────
    success, error_msg, warnings = _apply_upgraded_files(
        package_dir, updated, originals
    )
    report.warnings = warnings
    if not success:
        # Originals are untouched; keep the diff so the user can review.
        report.status = "apply_failed"
        report.message = f"upgrade apply failed: {error_msg}"
        return report
    diff_path.unlink(missing_ok=True)
    report.diff_path = None
    report.status = "applied"
    warn_prefix = ""
    if warnings:
        warn_prefix = "; ".join(warnings) + "; "
    report.message = (
        f"{warn_prefix}upgrade applied; the manifest changed — re-sign the "
        "package before publish (python -m stitch_plugin_tools sign)"
    )
    return report
